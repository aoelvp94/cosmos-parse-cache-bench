"""Astro CLI variant of the benchmark DAG.

For every synthetic dbt project under dags/dbt/<name>/ (generated by `just astro-projects`), define:
  cosmos_astro_<name>_dbt_ls        LoadMode.DBT_LS with Cosmos defaults (dbt ls cache in an Airflow Variable)
  cosmos_astro_<name>_dbt_manifest  LoadMode.DBT_MANIFEST from dags/dbt/<name>/target/manifest.json

The project path is relative to this file, as Cosmos recommends for Airflow 3 DAG bundles.
COSMOS_BENCH_DBT points at a dbt executable installed in its own virtualenv.
"""
import os
from datetime import datetime
from pathlib import Path

from cosmos import DbtDag, ExecutionConfig, ProfileConfig, ProjectConfig, RenderConfig
from cosmos.constants import InvocationMode, LoadMode

DBT_ROOT = (Path(__file__).parent / "dbt").absolute()
DBT = os.environ.get("COSMOS_BENCH_DBT", "/usr/local/airflow/dbt_venv/bin/dbt")
PROFILES = DBT_ROOT / "profiles.yml"

for project in sorted(p for p in DBT_ROOT.glob("*/") if (p / "dbt_project.yml").exists()):
    manifest = project / "target" / "manifest.json"
    for mode in (LoadMode.DBT_LS, LoadMode.DBT_MANIFEST):
        if mode is LoadMode.DBT_MANIFEST and not manifest.exists():
            continue
        dag_id = f"cosmos_astro_{project.name}_{mode.value}"
        globals()[dag_id] = DbtDag(
            dag_id=dag_id,
            project_config=ProjectConfig(
                dbt_project_path=project.as_posix(),
                manifest_path=manifest.as_posix() if mode is LoadMode.DBT_MANIFEST else None,
            ),
            profile_config=ProfileConfig(profile_name="bench", target_name="dev", profiles_yml_filepath=PROFILES),
            execution_config=ExecutionConfig(dbt_executable_path=DBT, invocation_mode=InvocationMode.SUBPROCESS),
            render_config=RenderConfig(load_method=mode, dbt_executable_path=DBT, invocation_mode=InvocationMode.SUBPROCESS),
            schedule=None,
            start_date=datetime(2026, 1, 1),
            catchup=False,
            tags=["cosmos-bench"],
        )
